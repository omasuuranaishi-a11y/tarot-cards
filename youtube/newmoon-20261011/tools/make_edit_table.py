"""full/timeline.json から 03_編集表.md を作り直す（全編の実装に合わせた編集表）。

    python tools/make_edit_table.py
"""
import json
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(os.path.join(root, "full", "timeline.json"), encoding="utf-8"))
MOVE = {"cam": "拡大・移動", "halo": "天体に丸", "seg": "サインの帯", "house": "ハウスの範囲", "line": "線を描く",
        "arc": "角度・度数の弧", "wedge": "範囲の表示", "text": "数値", "poly": "形を塗る", "callout": "注釈", "panel": "説明パネル"}


SCENE_MOVE = {"挿絵：夜空": "夜空がゆっくり流れる・文字", "図解：太陽・地球・月": "月が回り込み、太陽との角度が変わる",
              "挿絵：スマホ（日常の例）": "入力・削除・送信と、意味の札", "図解：時間軸": "日付と出来事が順に灯る",
              "図解：月の満ち欠け": "光が新月から満月へ半周する", "挿絵：天秤と二人": "天秤が傾き、最後に水平へ戻る",
              "挿絵：二人の会話": "会話の点が灯る・文字", "挿絵：窓明かり": "窓明かりがゆらぐ・文字",
              "挿絵：写真と手紙": "写真と手紙が広がり、順に光る", "図解：金星の公転と見かけの逆行": "公転に合わせて見かけの位置が動き、戻る区間を白で描く",
              "挿絵：水と火": "水面と火がゆらぐ・左右に文字", "挿絵：湖面の月": "水面の揺れで月の映り方が変わる",
              "挿絵：火": "火がゆらぐ・文字", "挿絵：サビアン": "灯りの下の二人・文字が順に出る",
              "挿絵：二つのシンボル": "左右に二つのシンボル・文字", "挿絵：手帳": "手帳に一行ずつ書かれる", "図解：期間の長さ": "期間の長さを棒で伸ばす"}


def mmss(t):
    t = int(t)
    return f"{t // 60}:{t % 60:02d}"


out = ["# 2026年10月11日 天秤座新月｜編集表 v2（全編 v1 の実装）", "",
       f"`full/index.html` の全編（約{mmss(data[-1]['end'])}・{sum(len(c['units']) for c in data)}場面）を、場面ごとに書き出した表です。",
       "`tools/make_edit_table.py` で `full/timeline.json` から作っているので、画面の定義（`full/chapters.js`）を変えたら作り直してください。",
       "", "## 共通ルール", "",
       "- チャートは「全体 → 該当天体を拡大 → 線を描く → 度数・オーブ → 象徴と解釈 → 具体例 → 図に戻る」を基本にする",
       "- 見出しは明朝、度数と説明はゴシック。文字は小さく上へ動きながら現れ、静かに止まる。場面はクロスフェード（0.8秒）でつなぎ、暗転は使わない",
       "- 右の説明パネルが出ている間は、チャートの右端をぼかして文字と重ねない。字幕は画面下の帯に入れる",
       "- ワイプは右下に丸いアイコンを置き、名前と中心をそろえる。挿絵・比較図の場面では下げる（あいさつと締めは出す）",
       "- 日常の例の場面には「日常の例です。配置が出来事を決めるわけではありません。」と小さく入れる",
       "- 天体の位置・度数・ハウスは計算値からの作図だけを使う。前回の満月の図も同じ計算（承認済みの値と一致）で描いている",
       "- 長さは毎分330字＋図を見せる間の仮の値。録音後は各単位の長さを実際の音声に合わせる", ""]
for c in data:
    out += [f"## {c['no']} {c['title']}（{mmss(c['start'])}〜{mmss(c['end'])}）", "",
            "| # | 時刻 | 長さ | 画面 | 注目対象 | 動き | 読む文 |", "|---|---|---:|---|---|---|---|"]
    for i, u in enumerate(c["units"], 1):
        moves = "・".join(MOVE[p] for p in u["parts"] if p in MOVE) or SCENE_MOVE.get(u["scene"], "—")
        if u["labels"]:
            moves += "（" + " / ".join(u["labels"]) + "）"
        focus = "・".join(u["focus"]) or "—"
        text = u["text"] if len(u["text"]) <= 60 else u["text"][:58] + "…"
        out.append(f"| {c['no']}-{i} | {mmss(u['start'])} | {u['end'] - u['start']:.0f}秒 | {u['scene']} | {focus} | {moves} | {text} |")
    out.append("")
out += ["## 実写素材に差し替えられる場面", "",
        "今回の挿絵はすべて自作です。満月のときの `stock/`（Mixkitの月・水面・二人・焚き火）が使える場合は、次の場面を差し替え候補にします。実写は当日の空や本人の体験として扱わず、必要なら「イメージ」と入れます。", "",
        "| 場面 | いまの挿絵 | 差し替え候補 |", "|---|---|---|",
        "| 01-1、13-4 | 夜空 | 月の実写 |", "| 04-3、09-6 | 二人の会話 | 二人の実写（街路の素材は「小道」の説明には使わない） |",
        "| 09-4 | 火 | 焚き火の実写 |", "| 11-8〜11-9、11-11 | 湖面の月 | 月と水面の実写 |", ""]
open(os.path.join(root, "03_編集表.md"), "w", encoding="utf-8").write("\n".join(out))
print("ok", len(out))
